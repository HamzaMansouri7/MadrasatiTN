"""Build parascolaire/outputs/PROGRESS.md: one row per theme, per output type, from the manifests and the files on disk.
Run: python parascolaire/tools/build_progress.py   (run dedupe_outputs.py first)
Statuses come from outputs/<classe>/<livre>/manifest.json (approved, approved_with_note, needs_redo, rejected, to_review)."""
import json, sys
from pathlib import Path

sys.stdout.reconfigure(encoding='utf-8')
sys.path.insert(0, str(Path(__file__).resolve().parent))
import export_notebooklm as EX
import build_runsheets as RS

OUT = RS.ROOT / 'outputs'
GOOD = ('approved', 'approved_with_note')
ICON = {'approved': 'OK', 'approved_with_note': 'OK*', 'needs_redo': 'REDO', 'rejected': 'REDO', 'to_review': '?'}


def pick(runs):
    """Best run: the newest approved one, else the newest run."""
    if not runs:
        return None
    ver = lambda r: int(r['file'].rsplit('__v', 1)[-1].split('.')[0])
    good = sorted((r for r in runs if r['status'] in GOOD), key=ver)
    return good[-1] if good else sorted(runs, key=ver)[-1]


def cell(best):
    if not best:
        return '-'
    v = best['file'].rsplit('__v', 1)[-1].split('.')[0]
    return f"{ICON.get(best['status'], best['status'])} v{v}"


lines = ['# Progress of generated outputs', '', 'Generated by `tools/build_progress.py`, do not edit by hand. OK = approved, OK* = approved with a note, REDO = needs a new generation, ? = not reviewed, - = not made.', '']
tot = {'infographic': 0, 'course-slides': 0, 'video': 0, 'themes': 0}
for bdir in sorted(EX.books().values()):
    mp = OUT / bdir.parent.name / bdir.name / 'manifest.json'
    if not mp.exists():
        continue
    folder = mp.parent
    man = json.loads(mp.read_text(encoding='utf-8'))
    book, themes = RS.analyse(bdir)
    files = {p.name for p in folder.iterdir()}
    vids = [f for f in files if '__video-enfant__' in f]
    lines += [f"## {book['title']} ({book['grade']})", '', '| # | Theme | Infographic | Course slides | Video | Notes |', '|---|---|---|---|---|---|']
    for t in themes:
        runs = [r for r in man['runs'] if r.get('sourceFile') == t['file']]
        ig = [r for r in runs if r['type'] == 'infographic']
        cs = [r for r in runs if r['type'] == 'course-slides']
        vd = [f for f in vids if f'__{t["file"][:-3]}__' in f]
        bi, bc = pick(ig), pick(cs)
        notes = '; '.join(r['notes'] for r in (bi, bc) if r and r.get('notes') and r['status'] != 'approved')
        lines.append(f"| {t['n']} | {t['theme']} | {cell(bi)} | {cell(bc)} | {'made' if vd else '-'} | {notes} |")
        tot['themes'] += 1; tot['infographic'] += bool(bi and bi['status'] in GOOD); tot['course-slides'] += bool(bc and bc['status'] in GOOD); tot['video'] += bool(vd)
    pdfs = sorted(f for f in files if f.endswith('.pdf'))
    lines += ['', f"Files in `outputs/{bdir.parent.name}/{bdir.name}/`: {sum(f.endswith('.png') for f in files)} PNG, {len(pdfs)} PDF, {len(vids)} video.", '']
lines += ['## Totals (approved only)', '', f"Themes: {tot['themes']} · infographic {tot['infographic']} · course slides {tot['course-slides']} · video {tot['video']}", '']
(OUT / 'PROGRESS.md').write_text('\n'.join(lines), encoding='utf-8')
print(f"PROGRESS.md written: themes {tot['themes']} | infographic OK {tot['infographic']} | course slides OK {tot['course-slides']} | video {tot['video']}")
